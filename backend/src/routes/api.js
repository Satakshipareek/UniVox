import { Router } from 'express';
import { z } from 'zod';
import Expense from '../models/Expense.js';
import Task from '../models/Task.js';
import Reminder from '../models/Reminder.js';
import { processVoiceCommand } from '../controllers/voiceController.js';
import { createExpense, listExpenses, expenseSummary, createTask, listTasks, completeTask, createReminder, listReminders } from '../services/actionService.js';
import { campusData } from '../services/campusData.js';
import { asyncHandler } from '../utils/asyncHandler.js';
const router = Router();
const sendCreated = (fn) => asyncHandler(async (req,res) => { const result = await fn(req.body); res.status(201).json({ success:true, data:result.data, message:result.message }); });
router.post('/voice/command', processVoiceCommand);
router.post('/expenses', sendCreated(createExpense));
router.get('/expenses', asyncHandler(async (req,res) => res.json({ success:true, data: await listExpenses(req.query.limit) })));
router.get('/expenses/summary', asyncHandler(async (req,res) => res.json({ success:true, data: await expenseSummary() })));
router.post('/tasks', sendCreated(createTask));
router.get('/tasks', asyncHandler(async (req,res) => res.json({ success:true, data: await listTasks(req.query.status) })));
router.patch('/tasks/:id/complete', asyncHandler(async (req,res) => res.json({ success:true, data: await completeTask(req.params.id), message:'Task marked as completed.' })));
router.post('/reminders', sendCreated(createReminder));
router.get('/reminders', asyncHandler(async (req,res) => res.json({ success:true, data: await listReminders() })));
router.get('/campus', (req,res) => res.json({ success:true, data:campusData }));
router.get('/health', (req,res) => res.json({ success:true, data:{ status:'ok', database: Expense.db.readyState === 1 ? 'connected' : 'disconnected', geminiConfigured:!!process.env.GEMINI_API_KEY, timestamp:new Date().toISOString() } }));
export default router;
